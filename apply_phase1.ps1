# Step 1: decode every file and check its sha256. Nothing is written yet.
$items = @()
foreach ($f in $files) {
    $clean = ($f.B64 -replace '\s', '')
    $bytes = [System.Convert]::FromBase64String($clean)
    $got = Get-Sha256Hex $bytes
    if ($got -ne $f.Sha) { throw ('Embedded file is damaged (sha256 mismatch): ' + $f.Path) }
    $items += @{ Path = $f.Path; Bytes = $bytes; Sha = $f.Sha }
}
Write-Host ('Checked ' + $items.Count + ' embedded files: all sha256 values match.')

# Step 2: look for conflicts. A file that already exists and is identical counts as done.
$conflicts = @()
$todo = @()
foreach ($i in $items) {
    $target = Join-Path $Root $i.Path.Replace('/', [string][System.IO.Path]::DirectorySeparatorChar)
    if (Test-Path $target) {
        $existing = [System.IO.File]::ReadAllBytes($target)
        if ((Get-Sha256Hex $existing) -eq $i.Sha) {
            Write-Host ('  already done: ' + $i.Path)
            continue
        }
        $conflicts += $i.Path
        continue
    }
    $todo += $i
}
if ($conflicts.Count -gt 0) {
    Write-Host 'STOP. These files already exist with different content. Nothing was written:'
    foreach ($c in $conflicts) { Write-Host ('  ' + $c) }
    throw 'Conflicts found'
}

# Step 3: write the new files (exact bytes, no BOM changes).
foreach ($i in $todo) {
    $target = Join-Path $Root $i.Path.Replace('/', [string][System.IO.Path]::DirectorySeparatorChar)
    $dir = Split-Path $target -Parent
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
    [System.IO.File]::WriteAllBytes($target, $i.Bytes)
    Write-Host ('  wrote: ' + $i.Path)
}

# Step 4: read every file back and check it again.
$bad = 0
foreach ($i in $items) {
    $target = Join-Path $Root $i.Path.Replace('/', [string][System.IO.Path]::DirectorySeparatorChar)
    if (-not (Test-Path $target)) { $bad++; Write-Host ('  MISSING: ' + $i.Path); continue }
    $back = [System.IO.File]::ReadAllBytes($target)
    if ((Get-Sha256Hex $back) -ne $i.Sha) { $bad++; Write-Host ('  DIFFERENT: ' + $i.Path) }
