# Step 1: decode every file and check its sha256. Nothing is written yet.
$items = @()
foreach ($f in $files) {
    $clean = ($f.B64 -replace '\s', '')
    $bytes = [System.Convert]::FromBase64String($clean)
    $got = Get-Sha256Hex $bytes
    if ($got -ne $f.Sha) { throw ('Embedded file is damaged (sha256 mismatch): ' + $f.Path) }
    $items += @{ Path = $f.Path; Bytes = $bytes; Sha = $f.Sha; Old = $f.Old }
}
Write-Host ('Checked ' + $items.Count + ' embedded files: all sha256 values match.')

# Step 2: look for conflicts.
#   new file, already identical        -> already done
#   new file, exists but different     -> conflict
#   replaced file, still the previous version -> will be replaced
#   replaced file, already the new one -> already done
#   replaced file, anything else       -> conflict
$conflicts = @()
$todo = @()
foreach ($i in $items) {
    $target = Join-Path $Root $i.Path.Replace('/', [string][System.IO.Path]::DirectorySeparatorChar)
    if (Test-Path $target) {
        $existing = Get-Sha256Hex ([System.IO.File]::ReadAllBytes($target))
        if ($existing -eq $i.Sha) { Write-Host ('  already done: ' + $i.Path); continue }
        if ($i.Old -ne '' -and $existing -eq $i.Old) { $todo += $i; continue }
        $conflicts += $i.Path
        continue
    }
    if ($i.Old -ne '') { $conflicts += ($i.Path + ' (expected to exist)'); continue }
    $todo += $i
}
if ($conflicts.Count -gt 0) {
    Write-Host 'STOP. These files are not in the expected state. Nothing was written:'
    foreach ($c in $conflicts) { Write-Host ('  ' + $c) }
    throw 'Conflicts found'
}

